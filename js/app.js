function renderPainPoints(){
  var grid=document.getElementById('painGrid');
  if(!grid) return;
  var catBrands=getBrandsInCategory(currentCategory);
  var themeNeg={},themePos={},themeBrands={};
  var dims=['产品质量','客户服务','物流配送','性价比','退货退款'];
  for(var i=0;i<dims.length;i++){themeNeg[dims[i]]=0;themePos[dims[i]]=0;themeBrands[dims[i]]=[];}

  for(var bi=0;bi<catBrands.length;bi++){
    var tb=catBrands[bi].theme_breakdown||{};
    for(var d=0;d<dims.length;d++){
      var dm=dims[d];
      var td=tb[dm];
      if(td){
        themeNeg[dm]+=Number(td.negative)||0;
        themePos[dm]+=Number(td.positive)||0;
        if((Number(td.negative)||0)>0) themeBrands[dm].push(catBrands[bi].name);
      }
    }
  }
  var cards=[];
  for(var t=0;t<dims.length;t++){
    var tn=dims[t];
    cards.push({theme:tn,neg:themeNeg[tn],pos:themePos[tn],brands:themeBrands[tn]});
  }
  cards.sort(function(a,b){return b.neg-a.neg;});

  var html='';
  for(var ci=0;ci<cards.length;ci++){
    var c=cards[ci];
    if(c.neg===0&&c.pos===0) continue;
    var topBrands=c.brands.slice(0,5);
    html+='<div class="pain-card">';
    html+='<div class="pc-theme">'+esc(c.theme)+'</div>';
    html+='<div class="pc-count">负面 '+c.neg+' 次 &middot; 正面 '+c.pos+' 次</div>';
    if(topBrands.length>0){
      html+='<div class="pc-brands">受影响: '+topBrands.map(function(n){return esc(n)}).join('、')+(c.brands.length>5?' 等'+c.brands.length+'品牌':'')+'</div>';
    }
    html+='</div>';
  }
  grid.innerHTML=html||'<div style="padding:20px;text-align:center;color:var(--text);font-size:.7rem">暂无痛点数据</div>';
}
