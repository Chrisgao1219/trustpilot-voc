// --- Biggest Movers ---
function renderBiggestMovers(){
  var rh=D.rating_history; if(!rh) return;
  var brands=D.brands||[]; if(!brands.length) return;
  var brandMap={}; for(var i=0;i<brands.length;i++) brandMap[brands[i].name]=brands[i];

  // Compute week-over-week change for each brand
  var changes=[];
  for(var name in rh){
    var pts=rh[name]; if(!pts||pts.length<2) continue;
    var latest=pts[pts.length-1].rating;
    var prev=pts[pts.length-2].rating;
    var diff=Math.round((latest-prev)*10)/10;
    // Stability: how many consecutive weeks same rating
    var stable=1;
    for(var j=pts.length-2;j>=0;j--){
      if(Math.abs(pts[j].rating-latest)<0.05) stable++;
      else break;
    }
    // Volatility: max-min over period
    var ratings=pts.map(function(p){return p.rating;});
    var vol=Math.round((Math.max.apply(null,ratings)-Math.min.apply(null,ratings))*10)/10;
    var b=brandMap[name]||{name:name,rating:latest};
    changes.push({name:name,displayName:b.displayName||name,rating:latest,diff:diff,stable:stable,vol:vol});
  }

  // Biggest improver
  changes.sort(function(a,b){return b.diff-a.diff;});
  var up=changes[0];
  // Biggest decliner
  changes.sort(function(a,b){return a.diff-b.diff;});
  var down=changes[0];
  // Most stable (min |diff|, highest stable count)
  changes.sort(function(a,b){return (Math.abs(a.diff)-Math.abs(b.diff))||(b.stable-a.stable);});
  var st=changes[0];
  // Most volatile
  changes.sort(function(a,b){return b.vol-a.vol;});
  var vol=changes[0];

  function setCard(id, brand, valTxt, subTxt){
    var el=document.getElementById(id); if(!el) return;
    if(!brand){ el.querySelector('.sv').textContent='—'; return; }
    el.querySelector('.sv').innerHTML='<span style="cursor:pointer" onclick="switchBrand(\''+esc(brand.name)+'\')" title="点击切换到 '+esc(brand.displayName||brand.name)+'">'+esc(brand.displayName||brand.name)+'</span>';
    el.querySelector('.ss').textContent=valTxt+(subTxt?' · '+subTxt:'');
  }
  setCard('mvUp', up, (up&&up.diff>0?'+'+up.diff.toFixed(1):'—'), up?up.rating.toFixed(1)+'/5':'');
  setCard('mvDown', down, (down&&down.diff<0?down.diff.toFixed(1):'—'), down?down.rating.toFixed(1)+'/5':'');
  setCard('mvStable', st, st?'连续'+st.stable+'周':'—', st?st.rating.toFixed(1)+'/5':'');
  setCard('mvVolatile', vol, vol?'±'+vol.vol.toFixed(1):'—', vol?vol.rating.toFixed(1)+'/5':'');
}


