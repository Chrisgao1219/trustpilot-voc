function sparkSVG(name){
  var hist=D.rating_history&&D.rating_history[name];
  if(!hist||hist.length<2) return '<svg class="spark-svg"><text x="0" y="14" font-size="8" fill="var(--text)">--</text></svg>';
  var pts=hist.slice(-8);
  var w=70,h=24,pad=4;
  var ratings=pts.map(function(p){return p.rating});
  var min=Math.min.apply(null,ratings)-0.2;
  var max=Math.max.apply(null,ratings)+0.2;
  var rng=max-min||1;
  var xs=pts.map(function(_,i){return pad+(w-2*pad)*i/(pts.length-1||1)});
  var ys=pts.map(function(_,i){return h-pad-(h-2*pad)*(ratings[i]-min)/rng});
  var line=pts.map(function(_,i){return (i===0?'M':'L')+xs[i].toFixed(1)+' '+ys[i].toFixed(1)}).join(' ');
  var dir='stable';
  if(ratings[ratings.length-1]>ratings[0]+0.15) dir='up';
  else if(ratings[ratings.length-1]<ratings[0]-0.15) dir='down';
  var dots='';
  for(var i=0;i<pts.length;i++){
    dots+='<circle cx="'+xs[i].toFixed(1)+'" cy="'+ys[i].toFixed(1)+'" r="1.5" class="spark-dot'+(i===pts.length-1?' last':'')+'"/>';
  }
  return '<svg class="spark-svg" viewBox="0 0 '+w+' '+h+'"><path d="'+line+'" class="spark-line '+dir+'"/>'+dots+'</svg>';
}


